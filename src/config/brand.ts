export function brandVariables(theme: "light" | "dark"): CSSProperties {
  return Object.fromEntries(
    Object.entries(brand.colors[theme]).map(([key, value]) => [
      "--" + key.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase()),
      value,
    ]),
  ) as CSSProperties;
}
